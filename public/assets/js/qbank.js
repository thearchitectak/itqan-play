// ===== أسئلة الرياضيات المتولدة =====
function near(x, spread = 5) { const s = new Set([x]); let k = 0; while (s.size < 4 && k++ < 50) { const d = (R(spread * 2 + 1) - spread) || 1; if (x + d >= 0) s.add(x + d); } while (s.size < 4) s.add(x + s.size * 3); return [...s]; }
export function mathQ(lvl = 1) {
  const t = R(lvl === 1 ? 3 : lvl === 2 ? 5 : 7);
  let q, ans, wrong;
  if (t === 0) { const a = 2 + R(lvl * 30), b = 2 + R(lvl * 30); q = `\u2066${a} + ${b} = ؟\u2069`; ans = a + b; }
  else if (t === 1) { const a = 10 + R(lvl * 40), b = 1 + R(a); q = `\u2066${a} − ${b} = ؟\u2069`; ans = a - b; }
  else if (t === 2) { const a = 2 + R(lvl === 1 ? 8 : 11), b = 2 + R(lvl === 1 ? 8 : 11); q = `\u2066${a} × ${b} = ؟\u2069`; ans = a * b; wrong = [a * (b + 1), a * (b - 1), (a + 1) * b].filter(x => x !== ans); }
  else if (t === 3) { const b = 2 + R(10), ans0 = 2 + R(10); q = `\u2066${b * ans0} ÷ ${b} = ؟\u2069`; ans = ans0; }
  else if (t === 4) { const a = 2 + R(9), b = 2 + R(9), c = 1 + R(20); q = `\u2066${a} × ${b} + ${c} = ؟\u2069`; ans = a * b + c; }
  else if (t === 5) { const p = [10, 20, 25, 50][R(4)], n = (2 + R(18)) * 20; q = `${p}% من ${n} = ؟`; ans = n * p / 100; }
  else { const x = 2 + R(15), a = 2 + R(9), b = R(30); q = `إذا كان ${a}س + ${b} = ${a * x + b}، فما قيمة س؟`; ans = x; }
  const opts = wrong && wrong.length >= 3 ? [ans, ...wrong.slice(0, 3)] : near(ans, Math.max(3, Math.round(ans * .15)));
  return { q, a: opts.map(String), cat: 'math', lvl, gen: true };
}

// اختيار مجموعة أسئلة: cats مصفوفة فئات، lvl المستوى الأقصى
export function pickQuestions(n, { cats = Object.keys(CATS), lvl = 2 } = {}) {
  const out = [];
  const pool = shuffle(STATIC.filter(q => cats.includes(q.cat) && q.lvl <= lvl).slice());
  const wantMath = cats.includes('math');
  let pi = 0;
  for (let i = 0; i < n; i++) {
    if (wantMath && (R(cats.length) === 0 || pi >= pool.length)) out.push(mathQ(1 + R(lvl)));
    else if (pi < pool.length) out.push(pool[pi++]);
    else out.push(mathQ(1 + R(lvl)));
  }
  // ترتيب الاختيارات عشوائيًا مع حفظ موضع الصحيحة
  return out.map(q => { const idx = shuffle([0, 1, 2, 3]); return { q: q.q, opts: idx.map(i => q.a[i]), ok: idx.indexOf(0), cat: q.cat, lvl: q.lvl }; });
}
